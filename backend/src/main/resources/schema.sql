-- Roda sempre ao ligar (spring.sql.init.mode=always).
-- "IF NOT EXISTS" só cria o que ainda não existe.

-- ===== USUÁRIOS: a única tabela que o Java grava =====
CREATE TABLE IF NOT EXISTS usuario (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome       VARCHAR(120) NOT NULL,
  email      VARCHAR(160) NOT NULL UNIQUE,
  senha_hash VARCHAR(100) NOT NULL,                      -- BCrypt, nunca a senha pura
  matricula  VARCHAR(30),
  turma      VARCHAR(60),
  perfil     VARCHAR(20)  NOT NULL DEFAULT 'USER',       -- USER ou ADMIN
  status     VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE',   -- PENDENTE, APROVADO, BLOQUEADO
  criado_em  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ===== Gravadas SÓ pelo Python =====
CREATE TABLE IF NOT EXISTS upload_lote (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  arquivo_nome    VARCHAR(255) NOT NULL,
  linhas_recebidas INTEGER     NOT NULL DEFAULT 0,
  linhas_validas  INTEGER      NOT NULL DEFAULT 0,
  linhas_invalidas INTEGER     NOT NULL DEFAULT 0,
  linhas_com_aviso INTEGER     NOT NULL DEFAULT 0,
  criado_em       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS consultor (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS segmento (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS servico (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS cliente (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo            VARCHAR(60)    NOT NULL UNIQUE,
  nome              VARCHAR(255)   NOT NULL,
  consultor_id      BIGINT REFERENCES consultor (id),
  segmento_id       BIGINT REFERENCES segmento (id),
  nivel             VARCHAR(20)    NOT NULL,
  faturamento_anual NUMERIC(15, 2) NOT NULL,
  data_contratacao  DATE           NOT NULL,
  cidade            VARCHAR(120),
  uf                VARCHAR(10),
  upload_lote_id    BIGINT REFERENCES upload_lote (id),
  atualizado_em     TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS contrato (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id BIGINT NOT NULL REFERENCES cliente (id) ON DELETE CASCADE,
  servico_id BIGINT NOT NULL REFERENCES servico (id),
  UNIQUE (cliente_id, servico_id)
);

CREATE TABLE IF NOT EXISTS estatistica_lote (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  upload_lote_id BIGINT       NOT NULL REFERENCES upload_lote (id) ON DELETE CASCADE,
  indicador      VARCHAR(80)  NOT NULL,
  valor          NUMERIC(18, 2),
  detalhe        VARCHAR(255)
);
