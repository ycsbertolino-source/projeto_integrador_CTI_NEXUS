CREATE TABLE IF NOT EXISTS upload_lote (
    id VARCHAR(36) PRIMARY KEY,
    arquivo_nome VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL,
    recebidas INTEGER NOT NULL,
    invalidas INTEGER NOT NULL,
    com_aviso INTEGER NOT NULL,
    mensagem_erro TEXT,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    concluido_em TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS estatistica_lote (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id VARCHAR(36) NOT NULL UNIQUE REFERENCES upload_lote(id),
    dados_json TEXT NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL,
    perfil VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    ultimo_acesso TIMESTAMP WITH TIME ZONE,
    token_version INTEGER NOT NULL DEFAULT 0
);
